"""Generate the C side's tables (mpc/core/tp_tables.[ch]) from src/torpedo/protocol.py.

    uv run python mpc/gen_tables.py          # rewrite them
    uv run python mpc/gen_tables.py --check  # exit 1 if they are out of date (the tests run this)

Only the commands the plugin may send are exported. The one flash write among them is QUERY_STORE
(`04 73 n`, a preset saved from the plugin's PRESET page after the user confirmed it); clear, IR
upload/delete and commit stay out, so C code can't send them by mistake.
"""

import sys
from pathlib import Path

from torpedo import protocol as P
from torpedo.device import MANUFACTURER, PID, VID

CORE = Path(__file__).resolve().parent / "core"
NOTICE = "/* Generated by mpc/gen_tables.py from src/torpedo/protocol.py: do not edit. */"

MESSAGES = """MSG_PARAM MSG_NAME MSG_QUERY MSG_EMPTY MSG_CAB MSG_INFO MSG_SETUP MSG_POLL
QUERY_INFO QUERY_BANK QUERY_NAMES QUERY_PARAMS QUERY_SETUP QUERY_STORE BANK_END NAMES_ALL NAMES_EDIT_BUFFER
SETUP_PRESET SETUP_PRESET_SOURCE EDIT_BUFFER CLIP_IN CLIP_OUT""".split()
NUMBERS = "REPORT_LEN PRESETS MIC_SLOT METER_FULL SIMULATION ARCADE IR IR_BANK".split()


def header() -> str:
    out = [NOTICE, "#pragma once", "#include <stdint.h>", "",
           f"#define TP_VID 0x{VID:04X}", f"#define TP_PID 0x{PID:04X}",
           f'#define TP_MANUFACTURER "{MANUFACTURER}"', ""]
    out += [f"#define TP_{n} 0x{getattr(P, n):02X}" for n in MESSAGES]
    out += [f"#define TP_HEARTBEAT 0x{P.HEARTBEAT[1]:02X}  /* 04 02 from the device */", ""]
    out += [f"#define TP_{n} {getattr(P, n)}" for n in NUMBERS]
    out += ["", f"#define TP_NPARAMS {len(P.PARAMS)}", "enum {"]
    out += [f"    TP_P_{p.name} = 0x{p.index:02X}," for p in P.PARAMS]
    out += ["};", "", f"#define TP_NSETUP {len(P.SETUP)}", "enum {"]
    out += [f"    TP_S_{name} = 0x{i:02X}," for i, name in enumerate(P.SETUP)]
    out += ["};", "",
            "typedef struct {",
            "    const char *name;",
            "    uint8_t lo, hi;",
            "    uint8_t writable;",
            "    uint8_t arcade;  /* editable in arcade mode (ARCADE_EDITABLE) */",
            "} tp_param_t;", "",
            "extern const tp_param_t tp_params[TP_NPARAMS];",
            "extern const char *const tp_setup_names[TP_NSETUP];",
            "/* Highest value of each global setting (SETUP_OPTIONS), -1: not written as a setting */",
            "extern const int8_t tp_setup_max[TP_NSETUP];", ""]
    return "\n".join(out)


def setup_max() -> list[int]:
    top = {o.index: max(o.wire_values) for o in P.SETUP_OPTIONS.values()}
    return [top.get(i, -1) for i in range(len(P.SETUP))]


def source() -> str:
    out = [NOTICE, '#include "tp_tables.h"', "",
           "const tp_param_t tp_params[TP_NPARAMS] = {"]
    out += [f'    {{"{p.name}", {p.lo}, {p.hi}, {int(p.writable)}, {int(p.index in P.ARCADE_EDITABLE)}}},'
            for p in P.PARAMS]
    out += ["};", "", "const char *const tp_setup_names[TP_NSETUP] = {"]
    out += [f'    "{name}",' for name in P.SETUP]
    out += ["};", "", "const int8_t tp_setup_max[TP_NSETUP] = {"]
    out += [f"    {v},  /* {name} */" for name, v in zip(P.SETUP, setup_max())]
    out += ["};", ""]
    return "\n".join(out)


def main() -> int:
    files = {CORE / "tp_tables.h": header(), CORE / "tp_tables.c": source()}
    if "--check" in sys.argv[1:]:
        stale = [f.name for f, text in files.items()
                 if not f.exists() or f.read_text(encoding="utf-8") != text]
        if stale:
            print(f"out of date: {', '.join(stale)} (run mpc/gen_tables.py)", file=sys.stderr)
        return int(bool(stale))
    for f, text in files.items():
        f.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())

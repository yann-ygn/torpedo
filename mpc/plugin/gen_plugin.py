def layout_conf() -> str:
    pg = Page()
    for page in (offline, simulation, arcade, ir):
        page(pg)
    out = [f"# {NOTICE}", "[tab TORPEDO]", *pg.lines]
    out += [f'qlinks "{name}" = {keys}' for name, keys in QLINKS.items()]
    return "\n".join(out) + "\n"


def main() -> int:
    params = vst_params()
    h, c = tables(params)
    files = {HERE / "params.json": json.dumps({"name": "Torpedo", "params": [e for e, _ in params]}, indent=1) + "\n",
             HERE / "plugin_tables.h": h, HERE / "plugin_tables.c": c, HERE / "layout.conf": layout_conf()}
    if "--check" in sys.argv[1:]:
        stale = [f.name for f, text in files.items() if not f.exists() or f.read_text(encoding="utf-8") != text]
        if stale:
            print(f"out of date: {', '.join(stale)} (run mpc/plugin/gen_plugin.py)", file=sys.stderr)
        return int(bool(stale))
    for f, text in files.items():
        f.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())

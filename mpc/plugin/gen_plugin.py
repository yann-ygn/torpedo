"""Generate the MPC plugin's parameter list and value texts from src/torpedo/layout.py.

    uv run python mpc/plugin/gen_plugin.py          # rewrite params.json, plugin_tables.[ch]
    uv run python mpc/plugin/gen_plugin.py --check  # exit 1 if any is out of date or layout.conf disagrees (the tests run this)

The VST parameter order is what MPC projects and skins bind to, so it only ever grows: the virtual `view`
first (MPC pokes parameter 0 on insert and on every STOP, and `view` ignores writes), `preset`, the Torpedo
parameters in protocol order (minus the preview and the pinned IR folders), the output level and mute, then
the steppers' prev/next triggers, then the PRESET page's: 16 tiles, the bank they show, the page's state, two
message lines, the action buttons, the name being typed, the name keyboard's keys and whether it shows.

`view` (offline / simulation / arcade / ir) is what the skin's `when=view:...` lines hang on. Each Torpedo parameter
also gets the modes whose layout.py page shows it: the engine drops writes in the others (a tab's Q-Links stay on its
controls whatever the mode, and only arcade mode refuses what it doesn't show by itself). The skin itself,
plugin/layout.conf, is not generated: it is designed in the skin studio (an MPC page is not the TUI's), and this
only checks it against the parameter list.
"""

import json
import re
import sys
from pathlib import Path

from torpedo import layout as L
from torpedo.protocol import NAME_CHARS, PARAMS, PARAM_BY_NAME, PRESETS, SETUP_OPTIONS

HERE = Path(__file__).resolve().parent
NOTICE = "Generated by mpc/plugin/gen_plugin.py from src/torpedo/layout.py: do not edit."

HIDDEN = {"SIMUHP_PREVIEW", "SIMUHP_FOLDER_IR_0", "SIMUHP_FOLDER_IR_1"}
VIEWS = ("offline", "simulation", "arcade", "ir")  # view = 1 + PRESET_MODE when connected
LIST_MAX = {L.CAB: 63, L.MIC: 7, L.IR_SLOT: 127}  # the unit's bank sizes bound them (the engine clamps)
PREFIX = {"CABINET": "Cabinet", "POWER AMP": "Amp", "EQ": "EQ", "REVERB": "Reverb", "PRESET": "Preset",
          "ARCADE": "Arcade", "ROOM": "Reverb", "IR LOADER": "Cabinet", "MICS": "Mic", "IR MIX": "IR"}
HEADS = {"SIMUHP_SPEAKER": "Cabinet", "SIMUAMP_MODELE": "Amp model", "EQ_MODE": "EQ mode", "REVERB_ROOM": "Reverb room"}
RENAME = {"ARCADE_LEVEL": "Arcade level"}  # "Preset level" is PRESET_LEVEL's
STEPPED = ("preset", "simuhp_speaker", "simuhp_mic", "simuhp_mic_2", "simuhp_wave0", "simuhp_wave1")
TILES = 16  # presets per bank page: the PRESET page's tiles (engine.c BANK_SIZE)
PUI = ("CLEAN", "EDITED", "PICK", "CONFIRM", "SAVING", "NAMING", "ASKSAVE")  # what the PRESET page offers (engine.c PUI_*)
ACTIONS = (("p_save", "Save preset"), ("p_saveas", "Save preset as"), ("p_discard", "Discard edits"),
           ("p_confirm", "Confirm"), ("p_cancel", "Cancel"), ("p_rename", "Rename preset"),
           ("p_name", "Edit name"))  # engine.c ACT_*
KEY_DEL, KEY_CLEAR = 0x08, 0x18  # the name keyboard's other keys (engine.c KEY_*); a character's key is its code


def key(name: str) -> str:
    return name.lower()


def named_controls() -> dict[str, tuple[str, L.Control, L.Row | None]]:
    """Torpedo parameter -> (VST name, control, row) from the first layout that shows it."""
    found: dict[str, tuple[str, L.Control, L.Row | None]] = {}

    def add(name: str, c: L.Control, row: L.Row | None = None):
        found.setdefault(c.param, (RENAME.get(c.param, name), c, row))

    for lay in (L.SIMULATION_LAYOUT, L.IR_LAYOUT, L.ARCADE_LAYOUT):
        for s in lay:
            prefix = PREFIX[s.title]
            if s.switch:
                add(f"{prefix} on", s.switch)
            if s.head:
                add(HEADS[s.head.param], s.head)
            entities = len(s.columns) == 2 and all(c[-2:] in (" A", " B") for c in s.columns)
            for r in s.rows:
                for i, c in enumerate(r.cells):
                    if len(r.cells) == 1:
                        add(f"{prefix} {r.label.lower()}" if s.title != "CABINET" else r.label, c, r)
                    elif entities:  # Mic A / Mic B: "Mic A", "Mic A side"
                        col = s.columns[i]
                        add(col if col.startswith(r.label) else f"{col} {r.label.lower()}", c, r)
                    else:  # EQ: "Band 1 freq"
                        add(f"{r.label} {s.columns[i].lower()}", c, r)
    add("Mode", L.MODE_CONTROL)
    return found


def shown_in() -> dict[str, int]:
    """Torpedo parameter -> a bit per PRESET_MODE whose layout shows it (the mode switch: every mode)."""
    modes = {L.MODE_CONTROL.param: (1 << len(L.LAYOUTS)) - 1}
    for mode, lay in L.LAYOUTS.items():
        for c in L.controls(lay):
            modes[c.param] = modes.get(c.param, 0) | 1 << mode
    return modes


def condition(c: L.Control, row: L.Row | None) -> bool:
    """Whether the control only means something in custom EQ mode (the only condition layout.py uses)."""
    conds = {f for f in (c.when, row.when if row else None) if f is not None}
    if conds - {L.eq_custom}:
        raise SystemExit(f"{c.param}: a layout condition gen_plugin.py doesn't know")
    return bool(conds)


def vst_params():
    """[(params.json entry, table row)] in VST order. A table row: kind, index, list, eq_custom, texts, otherwise, modes."""
    controls = named_controls()
    modes = shown_in()
    out = [({"key": "view", "name": "View", "options": [v.upper() for v in VIEWS]}, ("PP_VIEW", 0, None)),
           ({"key": "preset", "name": "Preset", "min": 1, "max": 128, "display": "int", "dynamic_display": True},
            ("PP_PRESET", 0, None))]
    for p in PARAMS:
        if p.name in HIDDEN:
            continue
        if p.name not in controls:
            raise SystemExit(f"{p.name} is in no layout")
        name, c, row = controls[p.name]
        entry = {"key": key(p.name), "name": name}
        texts, lst = None, None
        if c.kind == L.CHOICE:
            entry["options"] = [o.upper() for o in c.choices]
            if len(c.choices) != p.hi - p.lo + 1:
                raise SystemExit(f"{p.name}: {len(c.choices)} labels for {p.lo}..{p.hi}")
        elif c.kind in LIST_MAX:
            entry |= {"min": 0, "max": LIST_MAX[c.kind], "display": "int", "dynamic_display": True}
            lst = c.kind
        else:
            entry |= {"min": p.lo, "max": p.hi, "display": "int"}
            if c.fmt is not str:
                texts = [c.fmt(v) for v in range(p.lo, p.hi + 1)]
        custom = condition(c, row)
        other = ("-", "-")
        if custom:
            entry["dynamic_display"] = True
            if c.otherwise:
                other = tuple(c.otherwise({L.EQ_MODE: m}) for m in (0, 1))
        if texts:
            entry["dynamic_display"] = True
        out.append((entry, ("PP_PARAM", p.index, (lst, custom, texts, other, modes[p.name]))))
    level, mute = SETUP_OPTIONS["level"], SETUP_OPTIONS["mute"]
    out.append(({"key": "out_level", "name": "Output level", "min": level.lo, "max": level.hi, "display": "int",
                 "dynamic_display": True},
                ("PP_SETUP", level.index, (None, False, [L.level_db(v) for v in level.wire_values], ("-", "-"), 0))))
    out.append(({"key": "out_mute", "name": "Output mute", "options": [o.upper() for o in mute.choices]},
                ("PP_SETUP", mute.index, None)))
    names = {e["key"]: e["name"] for e, _ in out}
    for k in STEPPED:
        for side, delta in (("prev", -1), ("next", 1)):
            out.append(({"key": f"{k}_{side}", "name": f"{names[k]} {side}", "min": 0, "max": 1, "momentary": True,
                         "step_of": k, "step_delta": delta}, ("PP_TRIGGER", 0, None)))
    for n in range(TILES):
        out.append(({"key": f"slot_{n + 1}", "name": f"Slot {n + 1}", "display": "string"}, ("PP_SLOT", n, None)))
    out.append(({"key": "bank", "name": "Bank", "options": [f"{b * TILES + 1:03d}-{b * TILES + TILES:03d}"
                                                            for b in range(PRESETS // TILES)]}, ("PP_BANK", 0, None)))
    out.append(({"key": "pui", "name": "Preset page", "options": list(PUI)}, ("PP_PUI", 0, None)))
    for n, name in enumerate(("Message", "Message 2")):
        out.append(({"key": "pmsg" if n == 0 else "pmsg2", "name": name, "display": "string"}, ("PP_MSG", n, None)))
    for n, (k, name) in enumerate(ACTIONS):
        out.append(({"key": k, "name": name, "min": 0, "max": 1, "momentary": True}, ("PP_ACTION", n, None)))
    out.append(({"key": "pname", "name": "Name", "display": "string"}, ("PP_MSG", 2, None)))
    for code, k, name in keyboard():
        out.append(({"key": k, "name": name, "min": 0, "max": 1, "momentary": True}, ("PP_KEY", code, None)))
    out.append(({"key": "pkb", "name": "Name keyboard", "options": ["OFF", "ON"]}, ("PP_PUI", 1, None)))
    seen = [e["name"] for e, _ in out]
    if len(set(seen)) != len(seen):
        raise SystemExit(f"duplicate names: {sorted(n for n in seen if seen.count(n) > 1)}")
    return out


def keyboard() -> list[tuple[int, str, str]]:
    """The name keyboard's keys: (code, param key, param name). Characters are the ones preset names may hold."""
    keys = [(ord(c), f"k_{c.lower()}", f"Key {c}") for c in sorted(NAME_CHARS - {" "})]
    return keys + [(ord(" "), "k_space", "Key space"), (KEY_DEL, "k_del", "Key delete"), (KEY_CLEAR, "k_clear", "Key clear")]


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def tables(params) -> tuple[str, str]:
    h = [f"/* {NOTICE} */", "#pragma once", "#include <stdint.h>", "",
         "enum { PP_VIEW, PP_PRESET, PP_PARAM, PP_SETUP, PP_TRIGGER, PP_SLOT, PP_BANK, PP_PUI, PP_MSG, PP_ACTION, PP_KEY };",
         "enum { PP_LIST_NONE, PP_LIST_CAB, PP_LIST_MIC, PP_LIST_IR };", "",
         "typedef struct {",
         "    const char *key;             /* params.json */",
         "    uint8_t kind;                /* PP_* */",
         "    uint8_t index;               /* PP_PARAM: tp_params index, PP_SETUP: tp_setup_names index, PP_SLOT: tile,",
         "                                  PP_MSG: line, PP_ACTION: engine.c ACT_*, PP_KEY: character or engine.c KEY_* */",
         "    uint8_t list;                /* value text from the unit's banks: PP_LIST_* */",
         "    uint8_t eq_custom;           /* only meaningful in custom EQ mode, else otherwise[EQ_MODE] */",
         "    const char *const *text;     /* value text per value, or NULL */",
         "    int ntext;",
         "    const char *otherwise[2];    /* the text outside custom EQ mode (guitar, bass) */",
         "    uint8_t modes;               /* PP_PARAM: a bit per PRESET_MODE whose page shows it (writes in the others are dropped) */",
         "} pp_param_t;", "",
         f"#define PP_NPARAMS {len(params)}",
         "extern const pp_param_t pp_params[PP_NPARAMS];", ""]
    lists = {None: "PP_LIST_NONE", L.CAB: "PP_LIST_CAB", L.MIC: "PP_LIST_MIC", L.IR_SLOT: "PP_LIST_IR"}
    c = [f"/* {NOTICE} */", '#include "plugin_tables.h"', ""]
    rows, shared = [], {}  # one array per distinct text list
    for entry, (kind, index, extra) in params:
        lst, custom, texts, other, modes = extra or (None, False, None, ("-", "-"), 0)
        name = "0"
        if texts:
            if tuple(texts) not in shared:
                shared[tuple(texts)] = name = f"T{len(shared)}"
                c.append(f"static const char *const {name}[] = {{{', '.join(c_str(t) for t in texts)}}};")
            name = shared[tuple(texts)]
        rows.append(f'    {{{c_str(entry["key"])}, {kind}, {index}, {lists[lst]}, {int(custom)}, '
                    f'{name}, {len(texts) if texts else 0}, {{{c_str(other[0])}, {c_str(other[1])}}}, {modes}}},')
    c += ["", "const pp_param_t pp_params[PP_NPARAMS] = {", *rows, "};", ""]
    return "\n".join(h), "\n".join(c)


# --- layout.conf (hand-owned) ------------------------------------------------------------------------
# The skin is designed in mpc-vst-plugins' skin studio and edited by hand, so nothing here writes it: this only checks
# that it still agrees with the parameter list.

def check_layout(params) -> list[str]:
    """Problems in layout.conf: keys that are no parameter (a list's rows are <key>_1..N), conditions on what is no
    option of an option parameter, Q-Link sets that don't fit MPC's 4 x 4 grid."""
    entries = {e["key"]: e for e, _ in params}
    problems = []
    for n, line in enumerate((HERE / "layout.conf").read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("qlinks "):
            q = [k.strip() for k in line.split("=", 1)[1].split(",")]
            problems += [f"layout.conf:{n}: Q-Link key {k!r} is no parameter" for k in q if k != "-" and k not in entries]
            if len(q) > 16:
                problems.append(f"layout.conf:{n}: {len(q)} Q-Link keys (MPC has 16)")
            continue
        keys = re.findall(r"(?<!\w)(?:key|prev|next|get)=(\w+)", line)
        if line.startswith("list "):
            size = dict(re.findall(r"\b(cols|rows)=(\d+)", line))
            keys = [f"{k}_{i + 1}" for k in keys for i in range(int(size.get("cols", 1)) * int(size.get("rows", 1)))]
        problems += [f"layout.conf:{n}: {k!r} is no parameter" for k in keys if k not in entries]
        for m in re.finditer(r"when=(\w+):(\w+)", line):
            options = [o.upper() for o in entries.get(m.group(1), {}).get("options", [])]
            if m.group(2).upper() not in options and not (m.group(2).isdigit() and int(m.group(2)) < len(options)):
                problems.append(f"layout.conf:{n}: {m.group(0)!r}: no such option")
    return problems


def main() -> int:
    params = vst_params()
    h, c = tables(params)
    files = {HERE / "params.json": json.dumps({"name": "Torpedo", "params": [e for e, _ in params]}, indent=1) + "\n",
             HERE / "plugin_tables.h": h, HERE / "plugin_tables.c": c}
    problems = check_layout(params)
    for line in problems:
        print(line, file=sys.stderr)
    if "--check" in sys.argv[1:]:
        stale = [f.name for f, text in files.items() if not f.exists() or f.read_text(encoding="utf-8") != text]
        if stale:
            print(f"out of date: {', '.join(stale)} (run mpc/plugin/gen_plugin.py)", file=sys.stderr)
        return int(bool(stale or problems))
    for f, text in files.items():
        f.write_text(text, encoding="utf-8", newline="\n")
    return int(bool(problems))


if __name__ == "__main__":
    sys.exit(main())

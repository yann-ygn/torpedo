"""Generate the MPC plugin's parameter list, value texts and skin layout from src/torpedo/layout.py.

    uv run python mpc/plugin/gen_plugin.py          # rewrite params.json, layout.conf, plugin_tables.[ch]
    uv run python mpc/plugin/gen_plugin.py --check  # exit 1 if any is out of date (the tests run this)

The VST parameter order is what MPC projects and skins bind to, so it only ever grows: the virtual `view`
first (MPC pokes parameter 0 on insert and on every STOP, and `view` ignores writes), `preset`, the Torpedo
parameters in protocol order (minus the preview and the pinned IR folders), the output level and mute, then
the steppers' prev/next triggers.

`view` (offline / simulation / arcade / ir) is what every layout line hangs on (`when=view:...`): one page
per mode, switched by the unit's own mode, and a "not connected" page.
"""

import json
import sys
from pathlib import Path

from torpedo import layout as L
from torpedo.protocol import PARAMS, PARAM_BY_NAME, SETUP_OPTIONS

HERE = Path(__file__).resolve().parent
NOTICE = "Generated by mpc/plugin/gen_plugin.py from src/torpedo/layout.py: do not edit."

HIDDEN = {"SIMUHP_PREVIEW", "SIMUHP_FOLDER_IR_0", "SIMUHP_FOLDER_IR_1"}
VIEWS = ("offline", "simulation", "arcade", "ir")  # view = 1 + PRESET_MODE when connected
LIST_MAX = {L.CAB: 63, L.MIC: 7, L.IR_SLOT: 127}  # the unit's bank sizes bound them (the engine clamps)
PREFIX = {"CABINET": "Cabinet", "POWER AMP": "Amp", "EQ": "EQ", "REVERB": "Reverb", "PRESET": "Preset",
          "ARCADE": "Arcade", "ROOM": "Reverb", "IR LOADER": "Cabinet", "MICS": "Mic", "IR MIX": "IR"}
HEADS = {"SIMUHP_SPEAKER": "Cabinet", "SIMUAMP_MODELE": "Amp model", "EQ_MODE": "EQ mode", "REVERB_ROOM": "Reverb room"}
RENAME = {"ARCADE_LEVEL": "Arcade level"}  # "Preset level" is PRESET_LEVEL's
STEPPED = ("preset", "simuhp_speaker", "simuhp_mic", "simuhp_mic_2", "simuhp_wave0", "simuhp_wave1")


def key(name: str) -> str:
    return name.lower()


def named_controls() -> dict[str, tuple[str, L.Control, L.Row | None]]:
    """Torpedo parameter -> (VST name, control, row) from the first layout that shows it."""
    found: dict[str, tuple[str, L.Control, L.Row | None]] = {}

    def add(name: str, c: L.Control, row: L.Row | None = None):
        found.setdefault(c.param, (RENAME.get(c.param, name), c, row))

    for lay in (L.SIMULATION_LAYOUT, L.IR_LAYOUT, L.ARCADE_LAYOUT):
        for s in lay:
            prefix = PREFIX[s.title]
            if s.switch:
                add(f"{prefix} on", s.switch)
            if s.head:
                add(HEADS[s.head.param], s.head)
            entities = len(s.columns) == 2 and all(c[-2:] in (" A", " B") for c in s.columns)
            for r in s.rows:
                for i, c in enumerate(r.cells):
                    if len(r.cells) == 1:
                        add(f"{prefix} {r.label.lower()}" if s.title != "CABINET" else r.label, c, r)
                    elif entities:  # Mic A / Mic B: "Mic A", "Mic A side"
                        col = s.columns[i]
                        add(col if col.startswith(r.label) else f"{col} {r.label.lower()}", c, r)
                    else:  # EQ: "Band 1 freq"
                        add(f"{r.label} {s.columns[i].lower()}", c, r)
    add("Mode", L.MODE_CONTROL)
    return found


def condition(c: L.Control, row: L.Row | None) -> bool:
    """Whether the control only means something in custom EQ mode (the only condition layout.py uses)."""
    conds = {f for f in (c.when, row.when if row else None) if f is not None}
    if conds - {L.eq_custom}:
        raise SystemExit(f"{c.param}: a layout condition gen_plugin.py doesn't know")
    return bool(conds)


def vst_params():
    """[(params.json entry, table row)] in VST order. A table row: kind, index, list, eq_custom, texts, otherwise."""
    controls = named_controls()
    out = [({"key": "view", "name": "View", "options": [v.upper() for v in VIEWS]}, ("PP_VIEW", 0, None)),
           ({"key": "preset", "name": "Preset", "min": 1, "max": 128, "display": "int", "dynamic_display": True},
            ("PP_PRESET", 0, None))]
    for p in PARAMS:
        if p.name in HIDDEN:
            continue
        if p.name not in controls:
            raise SystemExit(f"{p.name} is in no layout")
        name, c, row = controls[p.name]
        entry = {"key": key(p.name), "name": name}
        texts, lst = None, None
        if c.kind == L.CHOICE:
            entry["options"] = [o.upper() for o in c.choices]
            if len(c.choices) != p.hi - p.lo + 1:
                raise SystemExit(f"{p.name}: {len(c.choices)} labels for {p.lo}..{p.hi}")
        elif c.kind in LIST_MAX:
            entry |= {"min": 0, "max": LIST_MAX[c.kind], "display": "int", "dynamic_display": True}
            lst = c.kind
        else:
            entry |= {"min": p.lo, "max": p.hi, "display": "int"}
            if c.fmt is not str:
                texts = [c.fmt(v) for v in range(p.lo, p.hi + 1)]
        custom = condition(c, row)
        other = ("-", "-")
        if custom:
            entry["dynamic_display"] = True
            if c.otherwise:
                other = tuple(c.otherwise({L.EQ_MODE: m}) for m in (0, 1))
        if texts:
            entry["dynamic_display"] = True
        out.append((entry, ("PP_PARAM", p.index, (lst, custom, texts, other))))
    level, mute = SETUP_OPTIONS["level"], SETUP_OPTIONS["mute"]
    out.append(({"key": "out_level", "name": "Output level", "min": level.lo, "max": level.hi, "display": "int",
                 "dynamic_display": True},
                ("PP_SETUP", level.index, (None, False, [L.level_db(v) for v in level.wire_values], ("-", "-")))))
    out.append(({"key": "out_mute", "name": "Output mute", "options": [o.upper() for o in mute.choices]},
                ("PP_SETUP", mute.index, None)))
    names = {e["key"]: e["name"] for e, _ in out}
    for k in STEPPED:
        for side, delta in (("prev", -1), ("next", 1)):
            out.append(({"key": f"{k}_{side}", "name": f"{names[k]} {side}", "min": 0, "max": 1, "momentary": True,
                         "step_of": k, "step_delta": delta}, ("PP_TRIGGER", 0, None)))
    seen = [e["name"] for e, _ in out]
    if len(set(seen)) != len(seen):
        raise SystemExit(f"duplicate names: {sorted(n for n in seen if seen.count(n) > 1)}")
    return out


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def tables(params) -> tuple[str, str]:
    h = [f"/* {NOTICE} */", "#pragma once", "#include <stdint.h>", "",
         "enum { PP_VIEW, PP_PRESET, PP_PARAM, PP_SETUP, PP_TRIGGER };",
         "enum { PP_LIST_NONE, PP_LIST_CAB, PP_LIST_MIC, PP_LIST_IR };", "",
         "typedef struct {",
         "    const char *key;             /* params.json */",
         "    uint8_t kind;                /* PP_* */",
         "    uint8_t index;               /* PP_PARAM: tp_params index, PP_SETUP: tp_setup_names index */",
         "    uint8_t list;                /* value text from the unit's banks: PP_LIST_* */",
         "    uint8_t eq_custom;           /* only meaningful in custom EQ mode, else otherwise[EQ_MODE] */",
         "    const char *const *text;     /* value text per value, or NULL */",
         "    int ntext;",
         "    const char *otherwise[2];    /* the text outside custom EQ mode (guitar, bass) */",
         "} pp_param_t;", "",
         f"#define PP_NPARAMS {len(params)}",
         "extern const pp_param_t pp_params[PP_NPARAMS];", ""]
    lists = {None: "PP_LIST_NONE", L.CAB: "PP_LIST_CAB", L.MIC: "PP_LIST_MIC", L.IR_SLOT: "PP_LIST_IR"}
    c = [f"/* {NOTICE} */", '#include "plugin_tables.h"', ""]
    rows, shared = [], {}  # one array per distinct text list
    for entry, (kind, index, extra) in params:
        lst, custom, texts, other = extra or (None, False, None, ("-", "-"))
        name = "0"
        if texts:
            if tuple(texts) not in shared:
                shared[tuple(texts)] = name = f"T{len(shared)}"
                c.append(f"static const char *const {name}[] = {{{', '.join(c_str(t) for t in texts)}}};")
            name = shared[tuple(texts)]
        rows.append(f'    {{{c_str(entry["key"])}, {kind}, {index}, {lists[lst]}, {int(custom)}, '
                    f'{name}, {len(texts) if texts else 0}, {{{c_str(other[0])}, {c_str(other[1])}}}}},')
    c += ["", "const pp_param_t pp_params[PP_NPARAMS] = {", *rows, "};", ""]
    return "\n".join(h), "\n".join(c)


